    // MARK: - Phase 60.5: end-of-quiz finale totals

    /// Phase 60.5: Counts + examples for the cinematic reveal + summary.
    /// Populated asynchronously by `loadFinaleTotals()` the moment the
    /// completion view renders. `hasLoaded` gates the summary's render
    /// so the user doesn't flash "0 vendors on file" for the half-
    /// second it takes the contractors fetch to resolve.
    @Published private(set) var finaleTotals: QuizFinaleTotals = .empty

    /// Phase 60.5: Fetch fresh counts of contractors + home systems,
    /// merge with `reconciliationTotals.added` (tasks added this quiz
    /// session), compute the projected protection value, and publish
    /// the result to `finaleTotals`. Idempotent — the completion view
    /// calls this in `.task` and we guard against re-firing via
    /// `finaleTotals.hasLoaded`.
    func loadFinaleTotals() async {
        guard !finaleTotals.hasLoaded else { return }

        // Build 90 fix: wait for the detached completion reconciler before
        // reading any counts. Without this we render "$0 / 0 tasks /
        // 2 vendors" because the reconciler's writes haven't landed yet.
        // `finalReconcileTask` is non-nil whenever `state.completedAt`
        // flipped during this session.
        await finalReconcileTask?.value

        var totals = QuizFinaleTotals()
        totals.hasLoaded = true

        // Build 90 fix: refresh the property from DB so any AVM that
        // ATTOM populated AFTER quiz init lands in `currentEstimatedValue`
        // for the projection below. The in-memory `property` is the
        // snapshot that was passed in at quiz start; address-hook
        // enrichment may have written newer values since.
        if let fresh = try? await db.fetchProperty(id: property.id) {
            self.property = fresh
        }

        // Build 90 fix: count `maintenance_tasks` from the DB rather than
        // the reconciler's in-session running total. The running total
        // misses tasks created inline (vehicle maintenance, hardscape, the
        // Phase 54A auto-created systems) and is empty when the user
        // resumes a quiz that crossed completion in a prior session.
        if let tasks = try? await db.fetchMaintenanceTasks(propertyId: property.id) {
            // `fetchMaintenanceTasks` already filters out archived rows
            // by default. The remaining set is what the user has on
            // their schedule going forward.
            totals.tasksScheduled = tasks.count
            totals.taskExamples = tasks
                .sorted { ($0.createdAt ?? .distantPast) > ($1.createdAt ?? .distantPast) }
                .prefix(3)
                .map(\.title)
        }

        // Gaps closed — we reuse the reconciler's "preserved" bucket
        // as a proxy for items the user explicitly confirmed the quiz
        // accounted for. Not perfect, but the count is a real number
        // pulled from real data rather than a fabrication.
        let preservedTitles = reconciliationTotals.preserved
        totals.gapsClosed = preservedTitles.count
        totals.gapExamples = Array(preservedTitles.suffix(3).reversed())

        // Vendors on file — fresh snapshot of the household's
        // contractors table. Captures everything the quiz captured
        // PLUS anything added before or alongside (e.g. vendor
        // mirrors from utility captures).
        if let contractors = try? await db.fetchContractors() {
            totals.vendorsOnFile = contractors.count
            totals.vendorExamples = contractors
                .sorted { ($0.createdAt ?? .distantPast) > ($1.createdAt ?? .distantPast) }
                .prefix(3)
                .map(\.companyName)
        }

        // Systems confirmed — same treatment for home_systems. The
        // reconciler + ensureAutoCreatedSystems collectively populate
        // this table during the quiz.
        if let systems = try? await db.fetchHomeSystems(propertyId: property.id) {
            let topLevel = systems.filter { $0.parentSystemId == nil }
            totals.systemsConfirmed = topLevel.count
            totals.systemExamples = topLevel
                .prefix(3)
                .map { "\($0.name) · \($0.category)" }
        }

        // Projected protection value — `estimatedValue × 0.12` per the
        // Remodeling Magazine + NAR maintenance-vs-neglect study (same
        // 12% figure codified in
        // `OnboardingScheduleGenerator.computeValueProtection`). Inlined
        // here rather than synthesizing a `PropertyLookupResult` since
        // the struct now has a custom `init(from:)` that suppresses the
        // memberwise initializer.
        //
        // Phase 95.1 fix: re-fetch the property here because
        // `currentEstimatedValue` is written by the property-lookup edge
        // function asynchronously after the onboarding initial property
        // insert. The `property` snapshot held by the view model is taken
        // at quiz-init time and may pre-date the ATTOM write — leaving
        // currentEstimatedValue nil and the cinematic reveal showing $0
        // for the entire HNW audience the reveal exists to delight.
        // Caught by overnight E2E test (Tests/e2e UI Wave 1 Subagent 5).
        let freshProperty = (try? await db.fetchProperty(id: property.id)) ?? property
        if let value = freshProperty.currentEstimatedValue, value > 0 {
            totals.projectedValueProtected = value * 0.12
        } else if let salePrice = freshProperty.purchasePrice, salePrice > 0 {
            // Fallback: project the last sale price forward at ~5%
            // appreciation/year when the canonical AVM is missing.
            // Matches the ladder in `computeValueProtection(from:)`.
            let yearsHeld = Self.yearsSince(freshProperty.purchaseDate) ?? 0
            let projected = salePrice * pow(1.05, Double(yearsHeld))
            totals.projectedValueProtected = projected * 0.12
        }

        finaleTotals = totals
    }

    /// Phase 60.5: Parse a "yyyy-MM-dd" / "MM/dd/yyyy" / "yyyy" date
    /// string into a full-year delta from today. Mirrors the helper
    /// on `OnboardingScheduleGenerator`. Used for the value-projection
    /// fallback when only a last-sale signal is available.
    private static func yearsSince(_ dateString: String?) -> Int? {
        guard let dateString else { return nil }
        let formatter = DateFormatter()
        for format in ["yyyy-MM-dd", "MM/dd/yyyy", "yyyy"] {
            formatter.dateFormat = format
            if let date = formatter.date(from: dateString) {
                let years = Calendar.current.dateComponents([.year], from: date, to: Date()).year ?? 0
                return max(0, years)
            }
        }
        return nil
    }

    /// Phase 60.3: Internal helper called from `persist(...)` right
    /// after the answer lands in state. Bumps `protectedValue` by the
    /// per-question delta and fires a soft haptic. SwiftUI animates the
    /// numeric transition via `.contentTransition(.numericText(...))` in
    /// the view.
    fileprivate func accreteValueMeter(for questionId: String, answer: HouseQuizAnswer) {
        let delta = HouseQuizValueMeter.delta(
            forQuestion: questionId,
            answer: answer,
            property: property,
            detectedSystems: detectedSystems
        )
        // Monotonic increase — never decrement the meter on answer edit.
        // If a user edits an earlier answer with a smaller delta, the
        // meter reflects the MAX earned across all answers rather than
        // the sum of current answers.
        protectedValue += delta
        Haptics.light()
    }

    /// Phase 67D (B1): bump the meter when the user confirms the ATTOM
    /// recap card. The "we already know your home" trust moment earns
    /// 5% of the home's estimated value as "Property baseline confirmed."
    /// Fires once per recap confirm; subsequent confirms (e.g. when a
    /// user back-navigates to the recap and re-confirms) are idempotent
    /// via `recapConfirmedDidAccrete` — we never double-count.
    func accreteAttomConfirmation() {
        guard !recapConfirmedDidAccrete else { return }
        recapConfirmedDidAccrete = true
        let baseline = (property.currentEstimatedValue ?? 500_000) * 0.05
        protectedValue += baseline
        Haptics.light()
    }

    /// Phase 67D (B1): one-shot guard so `accreteAttomConfirmation()`
    /// can't double-count if the user re-enters the recap surface.
    @Published private(set) var recapConfirmedDidAccrete: Bool = false

    private let mapper: HouseQuizAnswerMapper
    private let db = DatabaseService.shared

    init(property: PropertyRow) {
        self.property = property
        self.allQuestions = HouseQuizQuestionLibrary.allQuestions
        self.state = property.houseQuizState ?? HouseQuizState(startedAt: Date())
        self.mapper = HouseQuizAnswerMapper(householdId: property.householdId, propertyId: property.id)

        // Resume at the first unanswered+unsaved+unskipped question.
        self.currentIndex = firstUnresolvedIndex()
        // Phase 18b: A resumed quiz might land on a question whose dynamic
        // provider types resolve to empty (e.g. Q19 when Q3 was electric).
        // Mark it skipped and advance immediately so the user never sees a
        // dead picker.
        skipDynamicallyUnreachableQuestion()
        // Phase 19j: Same idea for dynamicSkip — if the resume cursor lands
        // on Q11b/Q14 but the user already answered Q11 with no_lawn, skip
        // those questions on resume too.
        skipDynamicallyHiddenQuestion()

        // Phase 19 — defensive background refresh: the dashboard's cached
        // PropertyRow may be stale (e.g. multi-device, fast resume). Adopt
        // any canonical DB state change, even when the answer count is the
        // same, so same-question edits do not keep showing stale local data.
        Task { @MainActor [weak self] in
            await self?.refreshAdminCatalog()
        }

        Task { @MainActor [weak self] in
            await self?.refreshPropertyStateFromDB()
        }

        // Build 86 — load the household's existing family members so the
        // Q28 caretakers flow can skip the spouse sub-step (and pre-populate
        // kids) when the user already added them via the dashboard "+"
        // button or the spouse invite flow on AccountCreationStep. Failures
        // leave the cache empty, which fails open: the view falls back to
        // showing the full Q28 flow as if no one was on file.
        Task { @MainActor [weak self] in
            await self?.refreshExistingFamilyMembers()
        }

        // Phase 60.1 — load the detected home systems so the new recap
        // card's "What we detected at your home" list renders without a
        // second network round trip from the view.
        Task { @MainActor [weak self] in
            await self?.loadDetectedSystemsIfNeeded()
        }

        // Phase 60.3 — restore the protection meter from persisted answers
        // so save-for-later resume lands the user back at the same value
        // they saw when they left. Silent (no haptic / animation) since
        // this is state hydration, not a user action.
        self.protectedValue = Self.restoreProtectedValue(
            from: state,
            property: property
        )
    }

    private func refreshAdminCatalog() async {
        let items = await AdminCatalogService.shared.refreshPublishedCatalog()
        let nextQuestions = AdminCatalogService.shared.quizQuestions(
            applying: items,
            to: HouseQuizQuestionLibrary.allQuestions
        )
        guard quizFingerprint(nextQuestions) != quizFingerprint(allQuestions) else { return }

        let currentQuestionId = currentQuestion?.id
        allQuestions = nextQuestions

        if let currentQuestionId,
           let retainedIndex = allQuestions.firstIndex(where: { $0.id == currentQuestionId }) {
            currentIndex = retainedIndex
        } else {
            currentIndex = firstUnresolvedIndex()
        }

        skipDynamicallyUnreachableQuestion()
        skipDynamicallyHiddenQuestion()
    }

    private func quizFingerprint(_ questions: [HouseQuizQuestion]) -> String {
        questions.map { question in
            [
                question.id,
                question.title,
                question.subtitle ?? "",
                question.kind.rawValue,
                question.chapter.rawValue,
                question.section.rawValue,
                question.answerOptions.map { "\($0.id):\($0.label)" }.joined(separator: "|"),
            ].joined(separator: "§")
        }.joined(separator: "¶")
    }

    /// Phase 60.3: Sum the `HouseQuizValueMeter.delta` for every answer in
    /// the persisted state so the running total rehydrates on view
    /// model init. Called from the designated initializer only — user-
    /// driven accretion happens via `accreteValueMeter(...)`.
    private static func restoreProtectedValue(
        from state: HouseQuizState,
        property: PropertyRow
    ) -> Double {
        guard !state.answers.isEmpty else { return 0 }
        return state.answers.reduce(0.0) { total, entry in
            total + HouseQuizValueMeter.delta(
                forQuestion: entry.key,
                answer: entry.value,
                property: property,
                detectedSystems: []
            )
        }
    }

    /// Phase 60.1: Load (or re-load) the detected home systems for this
    /// property. Silent failure leaves the array empty, which simply
    /// suppresses the detected-systems block on the recap card instead
    /// of blocking the quiz.
    func loadDetectedSystemsIfNeeded() async {
        do {
            detectedSystems = try await db.fetchHomeSystems(propertyId: property.id)
        } catch {
            print("[HouseQuiz] Failed to load detected systems: \(error)")
        }
    }

    /// Phase 60.1: Re-fetch the `PropertyRow` from the DB. Called by the
    /// `PropertyRecapEditSheet` after a save so every downstream reader
    /// (Q4 prefill, source caption, etc.) picks up the corrected value.
    /// Silent failure leaves the in-memory row untouched — the sheet has
    /// already surfaced the error if the update itself failed.
    func reloadProperty() async {
        do {
            property = try await db.fetchProperty(id: property.id)
        } catch {
            print("[HouseQuiz] Failed to reload property after edit: \(error)")
        }
    }

    /// Phase 60.1: Apply a fresh `PropertyRow` that the edit sheet already
    /// fetched from the DB. Use this when the updater returned the row —
    /// avoids a second fetch for the same data.
    func applyUpdatedProperty(_ fresh: PropertyRow) {
        property = fresh
    }

    private func refreshPropertyStateFromDB() async {
        do {
            let fresh = try await db.fetchProperty(id: property.id)
            guard let freshState = fresh.houseQuizState else { return }
            guard freshState != state else { return }

            property = fresh
            state = freshState
            currentIndex = firstUnresolvedIndex()
            skipDynamicallyUnreachableQuestion()
            // Phase 19j — same protection on the background refresh path.
            skipDynamicallyHiddenQuestion()
            print("[HouseQuiz] Refreshed state from DB: \(freshState.answers.count) answers, resume index \(currentIndex)")
        } catch {
            print("[HouseQuiz] Background state refresh failed: \(error)")
        }
    }

    /// Build 86 — refreshes the cached snapshot of `family_members` for the
    /// household. Called once on init so `caretakersBody` (Q28) can detect a
    /// pre-existing spouse / partner / child added via the dashboard "+"
    /// button or the AccountCreationStep invite flow and skip the
    /// duplicate-creating sub-steps. Silent failure leaves the cache empty,
    /// which fails open to showing the full Q28 form.
    func refreshExistingFamilyMembers() async {
        do {
            existingFamilyMembers = try await db.fetchFamilyMembers(householdId: property.householdId)
        } catch {
            print("[HouseQuiz] Failed to fetch existing family members: \(error)")
        }
    }

    /// Build 86 — true when the household already has at least one
    /// spouse-shaped relationship on file. Drives Q28's decision to skip the
    /// `QuizSpouseInviteInlineForm` sub-step entirely so re-running Q28
    /// doesn't create a second "Tom Burke" alongside an existing "Tom".
    var existingSpouseCount: Int {
        existingFamilyMembers.filter { member in
            let r = member.relationship.lowercased()
            return r == "spouse"
                || r == "partner"
                || r == "spouse/partner"
                || r == "husband"
                || r == "wife"
        }.count
    }

    /// Build 86 — pre-existing children on the household, sorted oldest
    /// first via the existing `sortedByAge` extension. Q28's kids sub-step
    /// uses this to seed `householdPendingKids` so the user sees their
    /// existing children as editable rows instead of being asked to add
    /// them all over again.
    var existingChildren: [FamilyMemberRow] {
        existingFamilyMembers.filter { member in
            let r = member.relationship.lowercased()
            return r == "child" || r == "son" || r == "daughter"
        }.sortedByAge()
    }

    // MARK: - Derived

    var currentQuestion: HouseQuizQuestion? {
        guard currentIndex >= 0, currentIndex < allQuestions.count else { return nil }
        return allQuestions[currentIndex]
    }

    var progress: Double {
        let total = allQuestions.count - state.skipped.count
        guard total > 0 else { return 1 }
        let answered = state.answers.count
        return min(1.0, Double(answered) / Double(total))
    }

    var progressLabel: String {
        // Apr 7, 2026 (build 82): switched from "X of Y done" to
        // "Question N of Y" so the user sees their CURRENT POSITION in
        // the quiz (1-indexed), not just a count of completed answers.
        // The previous label was easy to misread because the answer
        // count and the current position diverged once the user went
        // back to edit a previous question.
        //
        // Build 85: clamp position to total. When the quiz completes or the
        // user is in saved-review mode, currentIndex can reach or exceed
        // allQuestions.count (34), which made the label read "Question 35
        // of 34". Clamping keeps the math sane in every state. The view
        // also hides the toolbar progress bar entirely on completion and
        // saved-review screens, so this clamp is the belt to the toolbar
        // visibility's suspenders.
        let total = allQuestions.count
        let position = min(max(1, currentIndex + 1), total)
        let saved = state.savedForLater.count
        if saved > 0 {
            return "Question \(position) of \(total) · \(saved) saved"
        }
        return "Question \(position) of \(total)"
    }

    var isAtMilestone: Bool {
        HouseQuizQuestionLibrary.milestoneIndices.contains(currentIndex - 1)
    }

    /// Phase 85 (back-compat): "isComplete" historically meant "the quiz is
    /// fully done" and gated the cinematic reveal. With the intake/walk-
    /// through split, the cinematic only fires when the WALK-THROUGH
    /// completes — not at intake. So `isComplete` now reflects that
    /// stricter milestone. Surfaces that want the older "all questions
    /// answered" semantic should read `state.isIntakeComplete` instead.
    var isComplete: Bool {
        state.isWalkthroughComplete
    }

    /// Phase 85: every intake question answered (or skipped). Kept
    /// separately from `isComplete` so the path-decision screen can
    /// render after intake without triggering the cinematic.
    var isIntakeComplete: Bool {
