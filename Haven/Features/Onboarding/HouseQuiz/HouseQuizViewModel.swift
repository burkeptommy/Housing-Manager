                homeownerPresent: true,
                homeownerAccessNotes: nil,
                isExistingUserSupplement: false
            )
            savedAndReady = true
            Analytics.track(.quizMidQuizHandymanSwitched, [
                "answered": state.answers.count,
            ])
        } catch {
            saveErrorMessage = "Couldn't request the Chez handyman visit. Try again."
            Analytics.track(.quizMidQuizHandymanFailed, ["error": "\(error)", "stage": "request"])
        }
    }

    /// Chez v1: lightweight helper to read a property's `year_built`
    /// for ATTOM pre-fill in the post-quiz sweep prep. Returns nil if
    /// the row is missing or the column is null.
    private static func fetchYearBuilt(for propertyId: UUID) async -> Int? {
        let property = try? await DatabaseService.shared.fetchProperty(id: propertyId)
        return property?.yearBuilt
    }

    /// Phase 17b — runs `MaintenanceTaskReconciler.reconcileAll` on the
    /// quiz's property, merges the result into `reconciliationTotals`, and
    /// flips `finalReconciliationDidRun` so the completion view can render
    /// its real-numbers summary. Idempotent: subsequent calls are no-ops
    /// because of the flag check in `persist`.
    ///
    /// Build 87 note: the one-time chore-tracker template cleanup moved to
    /// `AppState.purgeDroppedTemplatesOnce()` so it runs once per device on
    /// auth resolution, not once per quiz completion. This path is now
    /// purely the reconcile pass.
    // Build 90: runFinalReconciliation inlined + detached in persistStateThrowing
    // to eliminate the 10-15s UI hang on quiz completion.

    private func advance() {
        // Show milestone card after questions 5, 10, 15, 20, 25, 30.
        if HouseQuizQuestionLibrary.milestoneIndices.contains(currentIndex) {
            showMilestoneCard = true
            return
        }
        moveNext()

        // Build 85: after moving forward, if there are no more fresh
        // questions but there are still saved-for-later questions on
        // file, route to the saved review screen instead of letting the
        // view fall through to the completion view (which would
        // misleadingly say "Quiz complete" while saved items are
        // parked invisibly). The same dead-end check fires from the
        // view's routing branch as a belt-and-suspenders for cases
        // where moveNext didn't go through advance() (e.g., goBack →
        // forward navigation, or a resume that landed past the end).
        if currentQuestion == nil && hasUnresolvedSavedQuestions {
            showSavedReviewScreen = true
        }
    }

    func dismissMilestoneAndContinue() {
        showMilestoneCard = false
        moveNext()
    }

    /// Build 84 — Fetches the forwarding email address for the current
    /// household via `DatabaseService.shared.fetchHouseholdEmailAddress()`
    /// and caches it for the Q17 milestone reveal. Called from the view's
    /// `.task` block on first appear so the address is loaded well before
    /// the user reaches Q17. Silent fail on error — if the fetch errors
    /// out, the Q17 milestone falls back to the generic milestone card.
    func loadForwardingEmailIfNeeded() async {
        guard cachedHouseholdEmail == nil else { return }
        do {
            cachedHouseholdEmail = try await db.fetchHouseholdEmailAddress()
        } catch {
            print("[HouseQuiz] Failed to fetch forwarding email: \(error)")
        }
    }

    /// Build 85: clear the persisted answer for a specific question. Used
    /// when the user taps the "Currently selected" pinned card on a
    /// providerSearch question to start over. The maintenance-task
    /// reconciler from earlier builds handles task cleanup; per-question
    /// cleanup of `utility_accounts` / `family_members` rows when
    /// re-answering is the Build 86 mapper-idempotency item.
    func clearAnswer(for questionId: String) async {
        state.answers.removeValue(forKey: questionId)
        await persistState()
    }

    // MARK: - Build 85: Saved-for-later review flow

    /// Build 85: true when the user has at least one saved-for-later
    /// question that hasn't been answered yet. Drives the trailing
    /// toolbar pill visibility and the dead-end auto-routing in
    /// `advance()` and the view body.
    var hasUnresolvedSavedQuestions: Bool {
        state.savedForLater.contains { questionId in
            state.answers[questionId] == nil
        }
    }

    /// Build 85: the list of saved-for-later questions that the user
    /// hasn't answered yet, resolved into the full HouseQuizQuestion
    /// objects so the saved review list can render section + title +
    /// chevron without re-looking-up the library on every cell render.
    var unresolvedSavedQuestions: [HouseQuizQuestion] {
        state.savedForLater.compactMap { questionId in
            guard state.answers[questionId] == nil else { return nil }
            return allQuestions.first(where: { $0.id == questionId })
        }
    }

    /// Build 85: returns the index of the next unanswered, non-saved,
    /// non-skipped question, or nil if every fresh question is resolved.
    /// Used by the saved review list's "Keep going forward instead"
    /// escape — when nil, that button hides because there's nowhere
    /// forward to go and the only paths are tap-a-saved-question or
    /// skip-all-and-finish.
    var firstUnresolvedFreshIndex: Int? {
        for (index, q) in allQuestions.enumerated() {
            if state.answers[q.id] == nil
                && !state.skipped.contains(q.id)
                && !state.savedForLater.contains(q.id) {
                return index
            }
        }
        return nil
    }

    /// Build 85: jump to a specific saved question from the review list.
    /// Removes it from `savedForLater` (it's no longer "saved", it's
    /// being actively answered now) and sets `currentIndex` to its
    /// position. Clears `showSavedReviewScreen` so the view routes back
    /// to the question screen.
    func jumpToSavedQuestion(_ question: HouseQuizQuestion) {
        state.savedForLater.removeAll { $0 == question.id }
        if let index = allQuestions.firstIndex(where: { $0.id == question.id }) {
            currentIndex = index
        }
        showSavedReviewScreen = false
        Task { await persistState() }
        Analytics.track(.quizSavedResumed, ["question_id": question.id])
    }

    /// Build 85: skip all remaining saved questions so the quiz can
    /// finish. Used from the saved review list's "Skip these and finish
    /// the quiz" footer button after a confirmation dialog. Adds every
    /// remaining unanswered saved question to `state.skipped`, clears
    /// the saved list, and re-fires persistence so the completion check
    /// runs against the updated state.
    func skipAllSavedAndFinish() {
        for questionId in state.savedForLater where state.answers[questionId] == nil {
            if !state.skipped.contains(questionId) {
                state.skipped.append(questionId)
            }
        }
        state.savedForLater.removeAll { state.answers[$0] == nil }
        showSavedReviewScreen = false
        Task {
            await persistState()
            // After persistence the completion check inside
            // persistStateThrowing has had its chance to flip
            // completedAt — but in case the user hadn't yet hit the
            // total threshold and now does post-skips, fall through to
            // the same check here so the second persist actually fires.
            let total = allQuestions.count - state.skipped.count
            let stillUnresolved = state.savedForLater.contains { state.answers[$0] == nil }
            if state.answers.count >= total, total > 0, !stillUnresolved, state.completedAt == nil {
                state.completedAt = Date()
                await persistState()
            }
        }
        Analytics.track(.quizSavedSkippedAll)
    }

    private func moveNext() {
        currentIndex += 1
        skipQuestionsAfterZeroVehicles()
        // Phase 18b: After advancing, also skip any provider-search question
        // whose dynamic types resolved to empty (Q19 with electric heat).
        skipDynamicallyUnreachableQuestion()
        // Phase 19j: also skip any question whose dynamicSkip closure
        // returns true based on prior answers (Q11b after no_lawn,
        // Q14 after no_lawn).
        skipDynamicallyHiddenQuestion()
    }

    /// Phase 19j — checks the current question's dynamicSkip closure and,
    /// if it returns true, marks it skipped and advances. Loops via
    /// moveNext() so consecutive skip-eligible questions all flush in one
    /// pass (e.g. Q11b and Q14 after a no_lawn answer).
    ///
    /// Phase 60.3: also accumulates a `pendingSkipToast` so the next
    /// rendered question acknowledges the auto-skip.
    func skipDynamicallyHiddenQuestion() {
        guard let q = currentQuestion else { return }
        guard let skipClosure = q.dynamicSkip else { return }
        guard skipClosure(state) else { return }
        if !state.skipped.contains(q.id) {
            state.skipped.append(q.id)
        }
        recordSkipForToast(reason: .previousAnswerMakesItIrrelevant)
        Task { await persistState() }
        moveNext()
    }

    /// Phase 60.3: Accumulate a skip into `pendingSkipToast` so the next
    /// question render shows "Skipped N questions" messaging. Merging
    /// same-reason skips lets consecutive dynamicSkip advances (e.g.
    /// Q11b + Q14 after no_lawn) surface as one toast instead of two.
    private func recordSkipForToast(reason: SkipReason) {
        if let existing = pendingSkipToast, existing.reason == reason {
            pendingSkipToast = SkipToastPayload(
                skippedCount: existing.skippedCount + 1,
                reason: reason
            )
        } else {
            pendingSkipToast = SkipToastPayload(skippedCount: 1, reason: reason)
        }
    }

    private func firstUnresolvedIndex() -> Int {
        // Phase 19 — also skip savedForLater questions, otherwise resume
        // lands the user back on the question they explicitly chose to defer.
        for (index, q) in allQuestions.enumerated() {
            if state.answers[q.id] == nil
                && !state.skipped.contains(q.id)
                && !state.savedForLater.contains(q.id) {
                return index
            }
        }
        return allQuestions.count
    }

    /// Apply the post-quiz reconcile + Day1 routing results onto the
    /// view-model. Pulled out of the inline `MainActor.run` so the
    /// outer `Task.detached { [weak self] in ... }` doesn't read a
    /// captured-var `self` across an await — that's the Swift 6
    /// strict-concurrency warning the compiler flags.
    @MainActor
    fileprivate func applyReconcileResult(
        result: MaintenanceTaskReconciler.ReconciliationResult,
        day1: Day1TaskCurator.Result,
        unverified: [HomeSystemRow]
    ) {
        if !result.isEmpty {
            reconciliationTotals = reconciliationTotals.merging(result)
        }
        if !day1.isEmpty {
            print("[HouseQuiz] Day1Curator: vendor=\(day1.vendorRouted) pendingVendor=\(day1.pendingVendorRouted) handyman=\(day1.handymanRouted) thisSeason=\(day1.remainingInThisSeason) routinesCreated=\(day1.routinesCreated)")
        }
        unverifiedSystemsForSweep = unverified
        installDateSweepNeeded = !unverified.isEmpty
        if unverified.isEmpty {
            installDateSweepDone = true
        }
        NotificationCenter.default.post(name: .maintenanceTaskChanged, object: nil)
        NotificationCenter.default.post(name: .routineChanged, object: nil)
    }
