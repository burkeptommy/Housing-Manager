    private func persist(answer: HouseQuizAnswer, for question: HouseQuizQuestion) async {
        isSaving = true
        defer { isSaving = false }

        // Apr 7, 2026 (build 82): capture the prior answer BEFORE we
        // overwrite local state. If the user is CHANGING a previously
        // answered question (e.g. asphalt → tile roof), we need to run
        // the reconciler after the new answer is applied so stale
        // home_systems / maintenance_tasks from the old answer get
        // cleaned up. Without this, switching answers leaves orphan
        // tasks in the property — the user ends up with both asphalt
        // AND tile roof inspections on their schedule. The reconciler
        // is idempotent and knows how to soft-delete tasks whose
        // template doesn't match the current confirmed subtype.
        let priorAnswer = state.answers[question.id]
        let isAnswerChange = priorAnswer != nil
            && (priorAnswer?.answerId != answer.answerId
                || priorAnswer?.selectedIds != answer.selectedIds
                || priorAnswer?.customText != answer.customText)

        // 1. Update local state immediately.
        state.answers[question.id] = answer
        state.savedForLater.removeAll { $0 == question.id }
        state.skipped.removeAll { $0 == question.id }

        // Phase 60.3: accrete the protection meter by the per-question
        // delta. Only fires on FIRST answer (not when the user edits an
        // answer they've already locked in) so the meter is monotonic.
        if priorAnswer == nil {
            accreteValueMeter(for: question.id, answer: answer)
        }

        // 2. Fire the answer mapper for DB side-effects. Capture any
        //    reconciler changes so the completion summary can show real
        //    numbers without faking them.
        let result = await mapper.apply(question: question, answer: answer)
        if !result.isEmpty {
            reconciliationTotals = reconciliationTotals.merging(result)
        }

        // 3. Persist quiz state JSONB.
        await persistState()

        // 4. Phase 17b — once the user has answered everything, run a
        //    full-property reconcile pass to catch any system whose subtype
        //    was inferred from sibling answers but never directly confirmed,
        //    plus orphaned legacy tasks. Notification posts so the dashboard
        //    refreshes its task counts.
        if state.completedAt != nil && !finalReconciliationDidRun {
            // Build 90: detach the reconciler so the completion screen
            // appears immediately instead of hanging for 10-15 seconds.
            //
            // Build 90 fix: keep a handle on the task (was fire-and-forget)
            // so `loadFinaleTotals()` can `await` it before reading the
            // counts that drive the cinematic reveal.
            finalReconciliationDidRun = true
            let propId = property.id
            let hhId = property.householdId
            finalReconcileTask = Task.detached(priority: .utility) { [weak self] in
                // Phase 54A: ensure the Vendor-Coverage-known-but-
                // quiz-silent systems (Handyman, Mosquito & Tick, Pet
                // Waste / Chimney / Snow Removal where applicable)
                // exist BEFORE the reconciler runs so their templates
                // get attached on this same pass.
                await HouseQuizAnswerMapper.ensureAutoCreatedSystems(
                    propertyId: propId,
                    householdId: hhId
                )
                let result = await MaintenanceTaskReconciler.reconcileAll(
                    propertyId: propId,
                    householdId: hhId
                )
                // Phase 66: Day1TaskCurator runs after reconcileAll so it
                // sees every freshly-seeded template task. Idempotent via
                // UserDefaults gate (hasRunDay1Curator_<propertyId>_v1) so
                // back-nav / re-completions don't re-route tasks that
                // already have a parent routine assigned.
                let day1 = await Day1TaskCurator.runIfNeeded(
                    propertyId: propId,
                    householdId: hhId
                )

                // Chez v1: ATTOM pre-fill runs RIGHT after Day1Curator
                // so the structural categories (roof, foundation,
                // crawl space) land with `source = 'estimated'` BEFORE
                // we compute the sweep list. The sweep then surfaces
                // these as one-tap confirms first, with everything
                // else queued behind.
                if let yearBuilt = await Self.fetchYearBuilt(for: propId) {
                    _ = await InstallDatePrefiller.prefill(
                        propertyId: propId,
                        yearBuilt: yearBuilt
                    )
                }

                // Compute which systems still need the user's
                // confirmation. Two cohorts:
                //   1. install_date_source IS NULL — never been asked
                //   2. ATTOM pre-fill landed and hasn't been confirmed
                //      yet (source = 'estimated' AND attom_prefilled
                //      AND confirmed_at IS NULL). One-tap accept first.
                let allSystems = (try? await DatabaseService.shared.fetchHomeSystems(propertyId: propId)) ?? []
                let unverified = allSystems
                    .filter { $0.parentSystemId == nil }
                    .filter { !SystemGroup.isServiceCategory($0.category) }
                    .filter { sys in
                        if sys.installDateSource == nil { return true }
                        if sys.installDateSource == "estimated"
                            && sys.installDateAttomPrefilled == true
                            && sys.installDateConfirmedAt == nil {
                            return true
                        }
                        return false
                    }
                    .sorted { lhs, rhs in
                        // ATTOM-prefilled rows (one-tap confirms) come
                        // first so the user gets early wins.
                        let lhsPrefilled = lhs.installDateAttomPrefilled == true
                        let rhsPrefilled = rhs.installDateAttomPrefilled == true
                        if lhsPrefilled != rhsPrefilled { return lhsPrefilled }
                        return lhs.displayName < rhs.displayName
                    }

                // Hop back to the actor and apply the results in one
                // method call. Calling `self?.applyReconcileResult(...)`
                // crosses the isolation boundary cleanly, so Swift 6
                // doesn't flag a captured-var-self read across an
                // await like an inline `MainActor.run` would.
                await self?.applyReconcileResult(
                    result: result,
                    day1: day1,
                    unverified: unverified
                )
            }
        } else if isAnswerChange {
            // Build 82 (Apr 7, 2026): the user changed a previously
            // committed answer. Run the reconciler in the background to
            // clean up tasks that match the OLD answer but not the new
            // one. Detached so the user doesn't wait for it; the
            // notification still fires when it completes so the
            // dashboard refreshes.
            let priorId: String = priorAnswer?.answerId ?? "nil"
            let newId: String = answer.answerId ?? "nil"
            print("[HouseQuiz] Answer changed for \(question.id) (\(priorId) → \(newId)). Running reconciler")
            let propId = property.id
            let hhId = property.householdId
            Task.detached(priority: .utility) {
                let result = await MaintenanceTaskReconciler.reconcileAll(
                    propertyId: propId,
                    householdId: hhId
                )
                print("[HouseQuiz] Change reconciler completed: \(result)")
                NotificationCenter.default.post(name: .maintenanceTaskChanged, object: nil)
            }
        }

        Analytics.track(.quizQuestionAnswered, [
            "question_id": question.id,
            "section": question.section.rawValue,
        ])
    }

    /// Phase 19 — throwing variant so callers (saveAndExit) can react to
    /// failures and surface them in the UI rather than silently dropping
    /// state on the floor.
    ///
    /// Build 85: completion now also requires that there are no
    /// unanswered saved-for-later questions. The user has to either
    /// answer or explicitly skip every saved item before
    /// `state.completedAt` flips. This is what stops the quiz from
    /// silently rendering "Quiz complete" while saved questions are
    /// still parked in `state.savedForLater` and would otherwise be
    /// invisible.
    private func persistStateThrowing() async throws {
        let total = allQuestions.count - state.skipped.count
        let hasUnresolvedSaved = state.savedForLater.contains { state.answers[$0] == nil }

        // Phase 85: when all intake questions are resolved, flip
        // intakeCompletedAt. The legacy `completedAt` field stays nil
        // until the WALKTHROUGH completes (per the new two-phase model)
        // — that's what gates the cinematic reveal.
        //
        // Back-compat: pre-Phase-85 rows have completedAt populated and
        // intakeCompletedAt copied forward by the model's resilient
        // decoder, so the quiz won't appear to "regress" for users who
        // already finished the old single-pass quiz.
        if state.answers.count >= total, total > 0, !hasUnresolvedSaved, state.intakeCompletedAt == nil {
            state.intakeCompletedAt = Date()
            Analytics.track(.quizCompleted)  // existing event — fires at intake completion
        }

        var update = PropertyUpdate()
        update.houseQuizState = state
        _ = try await db.updateProperty(id: property.id, update)
        NotificationCenter.default.post(name: .propertyChanged, object: nil)
    }

