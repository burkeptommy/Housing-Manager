export function getInitials(name: string): string {
  return name
    .split(' ')
    .map((n) => n[0])
    .join('')
    .toUpperCase()
    .slice(0, 2);
}

export function getPropertyImage(name: string): string {
  const lower = name.toLowerCase();
  if (lower.includes('malibu')) return images.properties.malibu;
  if (lower.includes('beverly')) return images.properties.beverly;
  if (lower.includes('scarsdale') || lower.includes('johnson'))
    return images.properties.scarsdale;
  return images.properties.greenwich;
}

export function getDestinationImage(dest: string): string {
  const lower = dest.toLowerCase();
  if (lower.includes('aspen') || lower.includes('colorado'))
    return images.travel.aspen;
  if (lower.includes('turks') || lower.includes('caicos'))
    return images.travel.turks;
  if (lower.includes('francisco') || lower.includes('sf'))
    return images.travel.sf;
  if (lower.includes('napa')) return images.travel.napa;
  return images.travel.aspen;
}

export function getServiceImage(service: string): string {
  const lower = service.toLowerCase();
  if (lower.includes('plumb') || lower.includes('pipe') || lower.includes('water'))
    return images.services.plumbing;
  if (lower.includes('electric') || lower.includes('wiring') || lower.includes('outlet'))
    return images.services.electrical;
  if (lower.includes('landscape') || lower.includes('garden') || lower.includes('lawn'))
    return images.services.landscaping;
  if (lower.includes('roof') || lower.includes('shingle') || lower.includes('gutter'))
    return images.services.roofing;
  return images.services.plumbing;
}

type VendorCategory = keyof typeof images.vendors;

/**
 * Get a unique vendor image based on category and index
 * @param category - The vendor's service category
 * @param index - Index to select different images within the same category
 */
export function getVendorImage(category: string, index: number = 0): string {
  const lower = category.toLowerCase();

  // Map category keywords to vendor image keys
  let categoryKey: VendorCategory = 'general';
  if (lower.includes('roof') || lower.includes('shingle') || lower.includes('gutter')) {
    categoryKey = 'roofing';
  } else if (lower.includes('plumb') || lower.includes('pipe') || lower.includes('drain')) {
    categoryKey = 'plumbing';
  } else if (lower.includes('electric') || lower.includes('wiring')) {
    categoryKey = 'electrical';
  } else if (lower.includes('landscape') || lower.includes('garden') || lower.includes('lawn')) {
    categoryKey = 'landscaping';
  } else if (lower.includes('hvac') || lower.includes('air') || lower.includes('heat') || lower.includes('cooling')) {
    categoryKey = 'hvac';
  } else if (lower.includes('pool') || lower.includes('spa')) {
    categoryKey = 'pool';
  } else if (lower.includes('clean') || lower.includes('maid') || lower.includes('housekeep')) {
    categoryKey = 'cleaning';
  } else if (lower.includes('paint') || lower.includes('drywall')) {
    categoryKey = 'painting';
  } else if (lower.includes('security') || lower.includes('alarm') || lower.includes('camera')) {
    categoryKey = 'security';
  } else if (lower.includes('floor') || lower.includes('tile') || lower.includes('hardwood')) {
    categoryKey = 'flooring';
  }

  const categoryImages = images.vendors[categoryKey];
  return categoryImages[index % categoryImages.length];
}
